const STR: Record<Lang, Table> = { en, ko };

function detect(): Lang {
	try {
		const v = localStorage.getItem(LANG_KEY);
		if (v === 'en' || v === 'ko') return v;
	} catch {
		// Storage can be unavailable; fall back to the system language.
	}
	return (navigator.language || 'en').toLowerCase().startsWith('ko') ? 'ko' : 'en';
}

export const LANG: Lang = typeof navigator === 'undefined' ? 'en' : detect();

export function setLang(lang: Lang): void {
	try {
		localStorage.setItem(LANG_KEY, lang);
	} catch {
		// Not persisted; the reload still shows the system language.
	}
}

export function t(key: string, vars: Record<string, string | number> = {}): string {
	const s = STR[LANG][key] ?? STR.en[key] ?? key;
	return typeof s === 'string' ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? '')) : key;
}

export function rows(key: string): [string, string][] {
	const s = STR[LANG][key] ?? STR.en[key];
	return Array.isArray(s) ? s : [];
}
